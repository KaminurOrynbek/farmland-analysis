let currentLocale = DEFAULT_LOCALE;

const normalizeLocale = (value) => (
  Object.values(LOCALES).includes(value) ? value : DEFAULT_LOCALE
);

const interpolate = (template, params = {}) => (
  Object.entries(params).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value ?? '')),
    template
  )
);

export const detectBrowserLocale = () => {
  if (typeof navigator === 'undefined') {
    return DEFAULT_LOCALE;
  }

  const browserLocale = navigator.language?.toLowerCase() || '';
  const localePrefix = browserLocale.split('-')[0];
  return BROWSER_LOCALE_PREFIXES[localePrefix] || DEFAULT_LOCALE;
};

export const getInitialLocale = () => {
  if (typeof window === 'undefined') {
    return DEFAULT_LOCALE;
  }

  const savedLocale = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  return normalizeLocale(savedLocale || detectBrowserLocale());
};

export const setCurrentLocale = (locale) => {
  currentLocale = normalizeLocale(locale);
};

export const getCurrentLocale = () => currentLocale;

export const getIntlLocale = (locale = currentLocale) => (
  INTL_LOCALES[normalizeLocale(locale)] || INTL_LOCALES[DEFAULT_LOCALE]
);

export const getDocumentLanguage = (locale = currentLocale) => (
  DOCUMENT_LANGUAGES[normalizeLocale(locale)] || DOCUMENT_LANGUAGES[DEFAULT_LOCALE]
);

export const t = (key, params = {}, locale = currentLocale) => {
  const normalizedLocale = normalizeLocale(locale);
  const localeDictionary = translations[normalizedLocale] || {};
  const template = localeDictionary[key] || key;
  return interpolate(template, params);
};

export const formatDate = (value, fallback = '\u2014', options = {}, locale = currentLocale) => {
  if (!value) {
    return fallback;
  }

  const parsed = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(parsed.getTime())) {
    return fallback;
  }

  return parsed.toLocaleDateString(getIntlLocale(locale), options);
};

export const formatDateTime = (value, fallback = '\u2014', options = {}, locale = currentLocale) => {
  if (!value) {
    return fallback;
  }

  const parsed = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(parsed.getTime())) {
    return fallback;
  }

  return parsed.toLocaleString(getIntlLocale(locale), options);
};

export const formatNumber = (value, options = {}, locale = currentLocale) => {
  const numeric = Number(value);
  if (!Number.isFinite(numeric)) {
    return '\u2014';
  }

  return new Intl.NumberFormat(getIntlLocale(locale), options).format(numeric);
};

export const formatInteger = (value, locale = currentLocale) => formatNumber(value, {
  maximumFractionDigits: 0
}, locale);

